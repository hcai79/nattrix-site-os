[CmdletBinding()]
param(
    [string]$Root = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'

function Assert-Property {
    param(
        [Parameter(Mandatory)]$Object,
        [Parameter(Mandatory)][string]$Name,
        [Parameter(Mandatory)][string]$Context
    )

    if (-not ($Object.PSObject.Properties.Name -contains $Name) -or [string]::IsNullOrWhiteSpace([string]$Object.$Name)) {
        throw "$Context is missing required property '$Name'."
    }
}

$sitesRoot = Join-Path $Root 'sites'
$registryPath = Join-Path $sitesRoot 'portfolio-registry.json'

if (-not (Test-Path -LiteralPath $registryPath)) {
    throw 'sites/portfolio-registry.json is required.'
}

$registry = Get-Content -Raw -LiteralPath $registryPath | ConvertFrom-Json
if (-not $registry.sites -or $registry.sites.Count -eq 0) {
    throw 'The portfolio registry must contain at least one site.'
}

$forbiddenPattern = '(?i)(sk-[a-z0-9_-]{20,}|ghp_[a-z0-9]{36,}|-----begin [a-z ]*private key-----|password\s*[:=]\s*\S+|application_password\s*[:=]\s*\S+)'

foreach ($entry in $registry.sites) {
    Assert-Property -Object $entry -Name 'site_key' -Context 'Registry entry'
    Assert-Property -Object $entry -Name 'manifest' -Context "Registry entry '$($entry.site_key)'"

    if ($entry.site_key -notmatch '^[a-z0-9]+(?:-[a-z0-9]+)*$') {
        throw "Site key '$($entry.site_key)' must be lowercase kebab-case."
    }

    $manifestPath = Join-Path $sitesRoot $entry.manifest
    if (-not (Test-Path -LiteralPath $manifestPath)) {
        throw "Manifest '$($entry.manifest)' does not exist."
    }

    $manifestRaw = Get-Content -Raw -LiteralPath $manifestPath
    if ($manifestRaw -match $forbiddenPattern) {
        throw "Manifest '$($entry.manifest)' appears to contain a secret."
    }

    $manifest = $manifestRaw | ConvertFrom-Json
    foreach ($property in @('site_key', 'display_name', 'public_url', 'cms', 'content_model', 'approval_policy', 'integrations')) {
        Assert-Property -Object $manifest -Name $property -Context "Manifest '$($entry.manifest)'"
    }

    if ($manifest.site_key -ne $entry.site_key) {
        throw "Manifest '$($entry.manifest)' does not match registry key '$($entry.site_key)'."
    }

    if ($manifest.cms -ne 'wordpress') {
        throw "Manifest '$($entry.manifest)' has unsupported CMS '$($manifest.cms)'."
    }

    if ($manifest.public_url -notmatch '^https://') {
        throw "Manifest '$($entry.manifest)' must use an HTTPS public URL."
    }
}

Write-Host "Validated $($registry.sites.Count) site package(s)."
